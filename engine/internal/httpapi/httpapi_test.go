// The dashboard shows this so that "the rate limit is silently not running" is
// something an operator sees, rather than something they discover after an
// incident.
func TestStatusReportsTheChainAndTheQueue(t *testing.T) {
	h := newHarness(t, nil, nil)
	h.engine.SetEnabled(map[string]bool{"sqli": true, "xss": false})

	status, body := get(t, h.server.URL+"/v1/status")
	if status != http.StatusOK {
		t.Fatalf("/v1/status = %d, want 200", status)
	}

	var out struct {
		Version string          `json:"version"`
		Chain   []string        `json:"chain"`
		Enabled map[string]bool `json:"enabled"`
		Audit   struct {
			Dropped  int64 `json:"dropped"`
			Capacity int   `json:"capacity"`
		} `json:"audit"`
	}
	if err := json.Unmarshal([]byte(body), &out); err != nil {
		t.Fatalf("decode status: %v — body was %s", err, body)
	}

	if out.Version != "test" {
		t.Errorf("version = %q, want %q", out.Version, "test")
	}
	if len(out.Chain) != 2 || out.Chain[0] != "sqli" {
		t.Errorf("chain = %v, want it in evaluation order", out.Chain)
	}
	if out.Enabled["xss"] {
		t.Error("enabled[xss] = true after it was switched off")
	}
	// The dropped counter is the only warning that the log is losing entries
	// under load, so it has to be reachable from outside the process.
	if out.Audit.Capacity != 256 {
		t.Errorf("audit.capacity = %d, want the configured buffer", out.Audit.Capacity)
	}
}

func TestRoutingRejectsTheWrongMethod(t *testing.T) {
	h := newHarness(t, nil, nil)

	// /v1/decide is registered for POST only. A GET reaching it would mean the
	// router is looser than the contract says.
	status, _ := get(t, h.server.URL+"/v1/decide")
	if status != http.StatusMethodNotAllowed {
		t.Fatalf("GET /v1/decide = %d, want 405", status)
	}
}

func get(t *testing.T, url string) (int, string) {
	t.Helper()

	resp, err := http.Get(url)
	if err != nil {
		t.Fatalf("GET %s: %v", url, err)
	}
	defer resp.Body.Close()

	body, _ := io.ReadAll(resp.Body)
	return resp.StatusCode, string(body)
}
