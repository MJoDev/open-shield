func postAudit(t *testing.T, h *harness, req auditRequest) (int, string) {
	t.Helper()

	body, err := json.Marshal(req)
	if err != nil {
		t.Fatalf("marshal: %v", err)
	}
	resp, err := http.Post(h.server.URL+"/v1/audit", "application/json", strings.NewReader(string(body)))
	if err != nil {
		t.Fatalf("POST /v1/audit: %v", err)
	}
	defer resp.Body.Close()

	out, _ := io.ReadAll(resp.Body)
	return resp.StatusCode, string(out)
}

// failingRepo is an in-memory log whose appends can be switched to failing, to
// exercise the paths where the store is unreachable.
type failingRepo struct {
	*audit.Memory
	fail atomic.Bool
}

func (r *failingRepo) Append(ctx context.Context, entry model.AuditEntry) error {
	if r.fail.Load() {
		return errors.New("audit store unavailable")
	}
	return r.Memory.Append(ctx, entry)
}

