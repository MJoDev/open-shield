// This server is the contract between proxy/lua/openshield.lua and the rules
// engine: the Lua hook posts a decideRequest and acts on the decideResponse.
// Nothing else in the system sits on the request path, so a change here that
// nobody notices is a change to what the proxy does with live traffic.
//
// Every test drives the real router, not the handler functions directly, so
// method and path routing are covered along with the bodies.

// --- Harness -----------------------------------------------------------------

type harness struct {
	server *httptest.Server
	repo   *audit.Memory
	writer *audit.Writer
	engine *rules.Engine
}

// newHarness wires a server over the real signature set and an in-memory log.
// ready defaults to healthy; pass a non-nil error to simulate a dependency
// being down.
func newHarness(t *testing.T, chain []rules.Rule, ready func() error) *harness {
	t.Helper()

	repo := audit.NewMemory()
	writer, err := audit.NewWriter(context.Background(), repo, audit.WriterOptions{Buffer: 256})
	if err != nil {
		t.Fatalf("NewWriter: %v", err)
	}

	if chain == nil {
		set, err := rules.LoadSignatures("")
		if err != nil {
			t.Fatalf("LoadSignatures: %v", err)
		}
		chain = []rules.Rule{
			rules.NewPatternRule("sqli", set.SQLi, 8192),
			rules.NewPatternRule("xss", set.XSS, 8192),
		}
	}
	engine := rules.New(chain)

	srv := httptest.NewServer(New(Options{
		Engine:  engine,
		Writer:  writer,
		Ready:   ready,
		Version: "test",
	}).Handler())
	t.Cleanup(srv.Close)
	// Close is idempotent, so a test that already drained through entries() is
	// unaffected; this only stops the append goroutine leaking from the rest.
	t.Cleanup(func() {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		_ = writer.Close(ctx)
	})

	return &harness{server: srv, repo: repo, writer: writer, engine: engine}
}

// decide posts a decision request and returns the parsed verdict.
func (h *harness) decide(t *testing.T, body any) (int, decideResponse) {
	t.Helper()

	var raw []byte
	switch v := body.(type) {
	case string:
		raw = []byte(v)
	default:
		var err error
		if raw, err = json.Marshal(v); err != nil {
			t.Fatalf("marshal request: %v", err)
		}
	}

	resp, err := http.Post(h.server.URL+"/v1/decide", "application/json", strings.NewReader(string(raw)))
	if err != nil {
		t.Fatalf("POST /v1/decide: %v", err)
	}
	defer resp.Body.Close()

	var out decideResponse
	if resp.StatusCode == http.StatusOK {
		if err := json.NewDecoder(resp.Body).Decode(&out); err != nil {
			t.Fatalf("decode response: %v", err)
		}
	} else {
		_, _ = io.Copy(io.Discard, resp.Body)
	}
	return resp.StatusCode, out
}

// entries flushes the writer and returns everything that reached the log. The
// append path is asynchronous by design (§8.2), so a test that reads the store
// without draining first is reading a race.
func (h *harness) entries(t *testing.T) []model.AuditEntry {
	t.Helper()

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	if err := h.writer.Close(ctx); err != nil {
		t.Fatalf("writer.Close: %v", err)
	}
	return h.repo.Entries()
}

