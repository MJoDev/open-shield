// The whole corpus is replayed through the HTTP surface, not just the rule
// chain, because the payload the log ends up with is built here.
func TestDecideRecordsEveryDecision(t *testing.T) {
	h := newHarness(t, nil, nil)

	cases := append(append([]corpus.Case{}, corpus.Attacks()...), corpus.Benign()...)
	for _, c := range cases {
		_, resp := h.decide(t, decideRequest{
			RequestID: c.ID,
			IP:        "203.0.113.7",
			Method:    c.HTTPMethod(),
			Path:      c.Path,
			Query:     c.Query,
			Host:      "ejemplo.test",
			Headers:   c.Headers,
			Body:      c.Body,
		})

		want := model.Block
		if c.Rule == "" {
			want = model.Allow
		}
		if resp.Verdict != want {
			t.Errorf("%s: verdict = %q, want %q", c.ID, resp.Verdict, want)
		}
	}

	entries := h.entries(t)
	if len(entries) != len(cases) {
		t.Fatalf("recorded %d entries for %d decisions — every decision goes on the record (RF-06)",
			len(entries), len(cases))
	}
	for _, entry := range entries {
		if entry.Kind != model.KindTraffic {
			t.Errorf("%s: kind = %q, want %q", entry.RequestID, entry.Kind, model.KindTraffic)
		}
	}
}

// TestAuditPayloadNeverCarriesTheBodyOrCredentials is the negative invariant of
// §6: the request body is inspected and then discarded, and the Cookie and
// Authorization headers never reach the store. An append-only log with long
// retention is the worst possible place for the passwords, tokens and personal
// data a POST carries — a log that keeps them is a credential store.
func TestAuditPayloadNeverCarriesTheBodyOrCredentials(t *testing.T) {
	h := newHarness(t, nil, nil)

	const (
		secretBody   = "usuario=maria&clave=SuperSecreto123"
		sessionToken = "session=abcdef0123456789"
		bearer       = "Bearer eyJhbGciOiJIUzI1NiJ9.payload.signature"
	)

	h.decide(t, decideRequest{
		RequestID: "req-secrets",
		IP:        "203.0.113.7",
		Method:    "POST",
		Path:      "/login",
		Host:      "ejemplo.test",
		Headers: map[string]string{
			"cookie":        sessionToken,
			"authorization": bearer,
			"user-agent":    "Mozilla/5.0",
		},
		Body: secretBody,
	})

	entries := h.entries(t)
	if len(entries) != 1 {
		t.Fatalf("recorded %d entries, want 1", len(entries))
	}

	// Serialise the whole payload and search it: checking individual keys would
	// miss a secret that a future change tucks into a nested field.
	raw, err := json.Marshal(entries[0].Payload)
	if err != nil {
		t.Fatalf("marshal payload: %v", err)
	}
	recorded := string(raw)

	for name, forbidden := range map[string]string{
		"the request body":          secretBody,
		"the password from it":      "SuperSecreto123",
		"the Cookie header":         sessionToken,
		"the Authorization header":  bearer,
		"the bearer token contents": "eyJhbGciOiJIUzI1NiJ9",
	} {
		if strings.Contains(recorded, forbidden) {
			t.Errorf("the audit payload contains %s\n  payload: %s", name, recorded)
		}
	}

	// What must survive: enough to identify the client and the request.
	headers, ok := entries[0].Payload["headers"].(map[string]any)
	if !ok {
		t.Fatalf("payload has no headers map: %s", recorded)
	}
	if headers["user-agent"] != "Mozilla/5.0" {
		t.Errorf("user-agent = %v, want it kept — it identifies the client", headers["user-agent"])
	}
	if _, present := headers["cookie"]; present {
		t.Error("the cookie header survived into the audit payload")
	}
	if _, present := headers["authorization"]; present {
		t.Error("the authorization header survived into the audit payload")
	}
}

// A block is only useful as evidence if the log says why. What is kept is the
// bounded excerpt around the match — the reason — and nothing more of the
// payload than that.
func TestAuditPayloadKeepsTheEvidenceForABlock(t *testing.T) {
	h := newHarness(t, nil, nil)

	h.decide(t, decideRequest{
		RequestID: "req-evidence",
		IP:        "198.51.100.4",
		Method:    "GET",
		Path:      "/buscar",
		Query:     "q=x%27%20UNION%20SELECT%20clave%20FROM%20usuarios--",
		Host:      "ejemplo.test",
	})

	entries := h.entries(t)
	if len(entries) != 1 {
		t.Fatalf("recorded %d entries, want 1", len(entries))
	}
	payload := entries[0].Payload

	for key, want := range map[string]any{
		"verdict": string(model.Block),
		"rule":    "sqli",
		"ip":      "198.51.100.4",
		"method":  "GET",
		"path":    "/buscar",
		"host":    "ejemplo.test",
	} {
		if got := fmt.Sprint(payload[key]); got != want {
			t.Errorf("payload[%q] = %q, want %q", key, got, want)
		}
	}

	reason, _ := payload["reason"].(string)
	if !strings.Contains(reason, "union_select") {
		t.Errorf("reason = %q, want it to name the signature that fired", reason)
	}
	if len(reason) > 512 {
		t.Errorf("reason is %d bytes; it is attacker-controlled input and must stay bounded", len(reason))
	}
}

